/**
 * Writes native/media/providers/higgsfield-models.ts: the Higgsfield models
 * Galta offers. Higgsfield's API lists no models; each model's page in its API
 * docs holds the authoritative input schema, so this copies those schemas
 * without their prose. Change the list, run `bun scripts/higgsfield-models.ts`,
 * and review the diff.
 */
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const DOCS = 'https://docs.higgsfield.ai/docs/models'
/** Endpoint id, name, kind, and the docs page that describes it. */
const MODELS = [
  ['higgsfield-ai/soul/v2/standard', 'Soul 2', 'image', 'soul-2/generate'],
  ['higgsfield-ai/soul/cinema', 'Soul Cinema', 'image', 'soul-cinema/generate'],
  ['marketing-studio/image', 'Marketing Studio Image', 'image', 'marketing-studio-image/generate-and-edit'],
  ['xai/grok-imagine-image-2.0', 'Grok Imagine Image 2', 'image', 'grok-image-2/generate-and-edit'],
  ['alibaba/qwen-image-3/edit', 'Qwen Image 3 Edit', 'image', 'qwen-image-3/edit'],
  ['ideogram/v4.0', 'Ideogram 4', 'image', 'ideogram-4/generate'],
  ['recraft/v4.1/text-to-image', 'Recraft 4.1', 'image', 'recraft-v4-1/text-to-image'],
  ['bytedance/seedance-2.5/text-to-video', 'Seedance 2.5 Text to Video', 'video', 'seedance-2-5/text-to-video'],
  ['bytedance/seedance-2.5/image-to-video', 'Seedance 2.5 Image to Video', 'video', 'seedance-2-5/image-to-video'],
  ['bytedance/seedance-2.5/reference-to-video', 'Seedance 2.5 Reference to Video', 'video', 'seedance-2-5/reference-to-video'],
  ['bytedance/seedance-2.5/video-edit', 'Seedance 2.5 Video Edit', 'video', 'seedance-2-5/video-edit'],
  ['bytedance/seedance-2.5/video-extend', 'Seedance 2.5 Video Extend', 'video', 'seedance-2-5/video-extend'],
  ['kling-video/v3.0/pro/text-to-video', 'Kling 3.0 Pro Text to Video', 'video', 'kling-3/pro-text-to-video'],
  ['kling-video/v3.0/pro/image-to-video', 'Kling 3.0 Pro Image to Video', 'video', 'kling-3/pro-image-to-video'],
  ['kling-video/o3/first-last-frame', 'Kling O3 First and Last Frame', 'video', 'kling-o3/first-last-frame'],
  ['alibaba/wan-3.0/text-to-video', 'Wan 3.0 Text to Video', 'video', 'wan-3/text-to-video'],
  ['alibaba/wan-3.0/image-to-video', 'Wan 3.0 Image to Video', 'video', 'wan-3/image-to-video'],
  ['minimax/h3/text-to-video', 'MiniMax H3 Text to Video', 'video', 'minimax-h3/text-to-video'],
  ['minimax/h3/image-to-video', 'MiniMax H3 Image to Video', 'video', 'minimax-h3/image-to-video'],
  ['minimax/hailuo-2.3/standard/text-to-video', 'Hailuo 2.3 Text to Video', 'video', 'hailuo-2-3/standard-text-to-video'],
  ['minimax/hailuo-2.3/standard/image-to-video', 'Hailuo 2.3 Image to Video', 'video', 'hailuo-2-3/standard-image-to-video'],
  ['higgsfield/cinema-studio/4.0', 'Cinema Studio 4.0', 'video', 'cinema-studio-4/generate']
] as const

const PROSE = new Set(['title', 'description', 'examples'])
const plain = (value: unknown): unknown => Array.isArray(value) ? value.map(plain)
  : value && typeof value === 'object' ? Object.fromEntries(Object.entries(value).filter(([name]) => !PROSE.has(name)).map(([name, inner]) => [name, plain(inner)]))
  : value

const models = []
for (const [id, name, kind, page] of MODELS) {
  const response = await fetch(`${DOCS}/${page}.md`)
  if (!response.ok) throw new Error(`${page}: HTTP ${response.status}`)
  const text = await response.text()
  if (!text.includes(`**Endpoint ID:** \`${id}\``)) throw new Error(`${page} does not describe ${id}`)
  const schema = /Complete JSON schema">\s*```json[^\n]*\n([\s\S]*?)```/.exec(text)?.[1]
  if (!schema) throw new Error(`${page} has no complete JSON schema`)
  models.push({ id, name, kind, input: plain(JSON.parse(schema)) })
}

await writeFile(join(import.meta.dir, '..', 'native', 'media', 'providers', 'higgsfield-models.ts'), `// Generated by scripts/higgsfield-models.ts from ${DOCS}; do not edit.
import type { MediaKind } from '../../../packages/canvas/src/capabilities/media'
import type { JsonSchema } from './endpoint'

export const HIGGSFIELD_MODELS: readonly { id: string; name: string; kind: Exclude<MediaKind, 'speech'>; input: JsonSchema }[] = ${JSON.stringify(models, null, 2)}
`)
console.log(`${models.length} Higgsfield models written`)
