test('manual image replacement removes obsolete agent attribution while preserving unrelated metadata', async ({ page }) => {
  const result = await page.evaluate(async data => {
    const w = window as any, scene = w.scene
    const { prepareImage, replaceImage } = await import('/canvas/imageImport.ts' as string)
    const [id] = await w.engineTest.import(data, { x: 300, y: 200 })
    scene.replace(scene.elements.map((element: any) => ({ ...element, customData: { note: 'Keep me', generatedPath: '/old.png', threadId: 'legacy', turnId: 'legacy-turn', executionId: 'old-execution', provenance: { providerId: 'mcp', sessionId: 'old-session' } } })))
    const target = scene.elements[0]
    const prepared = await prepareImage(scene, { url: data })
    replaceImage(scene, prepared, { id, versionNonce: target.versionNonce, restorationVersion: scene.restorationVersion })
    return scene.elements[0].customData
  }, png)
  expect(result).toEqual({ note: 'Keep me' })
})

test('imported and restored images paint immediately instead of waiting for the image-cache failsafe', async ({ page }) => {
  const red = 'data:image/svg+xml;base64,' + Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect width="100" height="100" fill="#e03131"/></svg>').toString('base64')
  await page.evaluate(async data => { const w = window as any; w.blank = w.scene.snapshot(); await w.engineTest.import(data, { x: 600, y: 400 }); w.imageSnapshot = w.scene.snapshot() }, red)
  const pixel = () => page.evaluate(() => {
    const c = [...document.querySelectorAll('canvas')].find(c => c.classList.contains('static'))!
    return [...c.getContext('2d')!.getImageData(600 * devicePixelRatio, 400 * devicePixelRatio, 1, 1).data].slice(0, 3)
  })
  await expect.poll(pixel, { timeout: 350, intervals: [16, 32, 64] }).toEqual([224, 49, 49])
  // Restore a different, uncached file before the engine's 500 ms failsafe.
  const green = 'data:image/svg+xml;base64,' + Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><rect width="100" height="100" fill="#2f9e44"/></svg>').toString('base64')
  await page.evaluate(dataURL => {
    const w = window as any, snapshot = structuredClone(w.imageSnapshot), oldFile = Object.values(snapshot.document.files)[0] as any
    const id = crypto.randomUUID()
    snapshot.document.elements[0].fileId = id
    snapshot.document.files = { [id]: { id, created: oldFile.created, mimeType: oldFile.mimeType, dataURL } }
    // A history scrub can replace element objects again while decoding the
    // same image is still pending. The final scene must paint that image.
    for (let i = 0; i < 8; i++) w.scene.restore(snapshot)
  }, green)
  await expect.poll(pixel, { timeout: 350, intervals: [16, 32, 64] }).toEqual([47, 158, 68])
})

test('SVG Blob assets paint without decoding object URLs as base64 and inline SVGs still normalize', async ({ page }) => {
  const errors: string[] = []
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('pageerror', error => errors.push(`${error.name}: ${error.message}`))
  const source = '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100"><title>\u753b\u5e03 \u2014 SVG</title><rect width="100" height="100" fill="#e03131"/></svg>'
  const dataURL = 'data:image/svg+xml;base64,' + Buffer.from(source).toString('base64')
  const result = await page.evaluate(async ({ source, dataURL }) => {
    const { scene, engineTest } = window as any
    const [id] = await engineTest.import(dataURL, { x: 600, y: 400 })
    const element = scene.elements.find((item: any) => item.id === id)
    const file = scene.files[element.fileId]
    const originalURL = file.dataURL
    const snapshot = scene.snapshot(), saved = snapshot.document.files[element.fileId]
    // Exercise the engine's original portable-file boundary alongside Blob assets.
    scene.api.addFiles([{ id: 'legacy-inline-svg', mimeType: 'image/svg+xml', dataURL, created: 1 }])
    const inline = scene.files['legacy-inline-svg']
    return {
      objectURL: originalURL.startsWith('blob:'),
      originalBytes: await file.blob.text() === source && await (await fetch(originalURL)).text() === source,
      savedBytes: await saved.blob.text() === source,
      portableURLPersisted: 'dataURL' in saved,
      inlineNormalized: (await (await fetch(inline.dataURL)).text()).includes('viewBox="0 0 100 100"'),
      inlineVersion: inline.version
    }
  }, { source, dataURL })
  expect(result).toEqual({ objectURL: true, originalBytes: true, savedBytes: true, portableURLPersisted: false, inlineNormalized: true, inlineVersion: 2 })
  await expect.poll(() => page.evaluate(() => {
    const canvas = document.querySelector<HTMLCanvasElement>('canvas.excalidraw__canvas.static')!
    return [...canvas.getContext('2d')!.getImageData(600 * devicePixelRatio, 400 * devicePixelRatio, 1, 1).data].slice(0, 3)
  })).toEqual([224, 49, 49])
  expect(errors).toEqual([])
})
