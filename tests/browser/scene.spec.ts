test('a failed agent save never enters the scene or rolls back later drawing and history', async ({ page }) => {
  await page.goto('/dev/scene-test.html')
  await page.waitForFunction(() => Boolean((window as any).engineTest))
  const result = await page.evaluate(async () => {
    const w = window as any, t = w.engineTest, s = w.scene, blank = s.snapshot()
    const failures: string[] = [], snapshots: any[] = []
    for (const restore of [false, true]) {
      s.restore(blank)
      let release!: () => void
      w.saveGate = new Promise<void>(resolve => { release = resolve }); w.failSave = true
      const entered = new Promise<void>(resolve => { w.saveEntered = resolve })
      const pending = t.tool('canvas_edit', { revision: t.revision(), operations: [{ type: 'create_text', text: 'Agent edit', x: 200, y: 200 }] })
      await entered
      if (restore) s.restore(blank)
      else t.apply([{ type: 'create_text', text: 'Later user edit', x: 400, y: 200 }])
      const beforeFailure = JSON.stringify(s.snapshot().document)
      release()
      try { await pending } catch (error) { failures.push(String(error)) }
      snapshots.push({ unchanged: beforeFailure === JSON.stringify(s.snapshot().document), count: s.elements.length })
    }
    return { failures, snapshots }
  })
  expect(result.snapshots).toEqual([{ unchanged: true, count: 1 }, { unchanged: true, count: 0 }])
  expect(result.failures).toHaveLength(2)
  for (const failure of result.failures) expect(failure).toContain('Storage unavailable')
})
