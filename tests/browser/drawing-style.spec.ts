import { acceptanceOrigin } from '../../scripts/lib/acceptance'
import { test, expect, type Page } from '@playwright/test'
import { historyWorkspace } from './history-helpers'

async function choose(page: Page, label: string, option: string) {
  await page.getByRole('combobox', { name: label, exact: true }).click()
  await page.getByRole('option', { name: option, exact: true }).click()
}


test('drawing style edits the selected shape and exposes fill patterns only when relevant', async ({ page }) => {
  await page.goto(`${acceptanceOrigin}/sidepanel/index.html`)
  await page.getByRole('button', { name: 'Shapes and more tools', exact: true }).click()
  await page.getByRole('button', { name: 'Rectangle', exact: true }).click()
  await page.mouse.move(400, 240)
  await page.mouse.down()
  await page.mouse.move(600, 390, { steps: 5 })
  await page.mouse.up()
  await expect(page.getByRole('region', { name: 'Galta canvas, 1 objects', exact: true })).toBeVisible()
  const shape = async () => {
    const w = await historyWorkspace(page)
    return w.snapshots[w.project.headCommitId].document.elements.find((e: any) => !e.isDeleted)
  }
  await expect.poll(shape).toMatchObject({ type: 'rectangle' })
  const trigger = page.getByRole('button', { name: 'Drawing style', exact: true })
  await trigger.click()
  const panel = page.getByRole('dialog', { name: 'Drawing style', exact: true })
  await expect(panel.getByRole('combobox', { name: 'Pattern', exact: true })).toHaveCount(0)
  await panel.getByRole('button', { name: 'Stroke Clay', exact: true }).click()
  await expect.poll(async () => (await shape()).strokeColor).toBe('#b65f46')
  await panel.getByRole('button', { name: 'Drawing Precise', exact: true }).click()
  await expect.poll(async () => (await shape()).roughness).toBe(0)
  const width = panel.getByRole('slider', { name: 'Stroke width', exact: true })
  await width.focus()
  await width.press('End')
  await expect(width).toHaveAttribute('aria-valuetext', '16px')
  await expect.poll(async () => (await shape()).strokeWidth).toBe(16)
  await panel.getByRole('button', { name: 'Fill Sage', exact: true }).click()
  await expect(panel.getByRole('combobox', { name: 'Pattern', exact: true })).toBeVisible()
  await choose(page, 'Pattern', 'Cross-hatch')
  await expect.poll(async () => (await shape()).fillStyle).toBe('cross-hatch')
  const opacity = panel.getByRole('slider', { name: 'Opacity', exact: true })
  await opacity.focus()
  await opacity.press('ArrowLeft')
  await expect(opacity).toHaveAttribute('aria-valuetext', '99%')
  await expect.poll(async () => (await shape()).opacity).toBe(99)
  await panel.getByRole('button', { name: 'Fill None', exact: true }).click()
  await expect(panel.getByRole('combobox', { name: 'Pattern', exact: true })).toHaveCount(0)
  await expect.poll(async () => (await shape()).backgroundColor).toBe('transparent')
  await panel.getByRole('button', { name: 'Fill Sage', exact: true }).click()
  await expect(panel.getByRole('combobox', { name: 'Pattern', exact: true })).toHaveText('Cross-hatch')
  await expect.poll(async () => (await shape()).backgroundColor).toBe('#d9e0cf')
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await page.reload()
  await expect(page.getByRole('region', { name: 'Galta canvas, 1 objects', exact: true })).toBeVisible()
  expect(await shape()).toMatchObject({ strokeColor: '#b65f46', roughness: 0, strokeWidth: 16, backgroundColor: '#d9e0cf', fillStyle: 'cross-hatch', opacity: 99 })
})

async function elements(page: import('@playwright/test').Page) {
  const w = await historyWorkspace(page)
  return w.snapshots[w.project.headCommitId].document.elements.filter((el: any) => !el.isDeleted)
}
async function textAt(page: import('@playwright/test').Page, x: number, y: number, text: string) {
  await page.getByRole('button', { name: 'Text — T', exact: true }).click()
  await page.mouse.click(x, y)
  await page.locator('.excalidraw-wysiwyg').fill(text)
  await page.keyboard.press('Escape')
}
async function selectAll(page: import('@playwright/test').Page) {
  await page.getByRole('button', { name: 'Select — V', exact: true }).click()
  await page.locator('.excalidraw').focus()
  await page.keyboard.press('Meta+a')
}

test('eraser is a primary tool with native undo, redo and persistence', async ({ page }) => {
  await page.goto(`${acceptanceOrigin}/sidepanel/index.html`)
  const eraser = page.getByRole('button', { name: 'Erase — E', exact: true })
  await expect(eraser).toBeVisible()
  await page.getByRole('button', { name: 'Draw — P', exact: true }).click()
  await page.mouse.move(400, 250); await page.mouse.down(); await page.mouse.move(600, 350, { steps: 8 }); await page.mouse.up()
  await expect.poll(async () => (await elements(page)).length).toBe(1)
  await eraser.click()
  await expect(eraser).toHaveAttribute('aria-pressed', 'true')
  await page.mouse.move(480, 250); await page.mouse.down(); await page.mouse.move(480, 350, { steps: 10 }); await page.mouse.up()
  await expect.poll(async () => (await elements(page)).length).toBe(0)
  await page.locator('.excalidraw').focus(); await page.keyboard.press('Meta+z')
  await expect.poll(async () => (await elements(page)).length).toBe(1)
  await page.keyboard.press('Meta+Shift+z')
  await expect.poll(async () => (await elements(page)).length).toBe(0)
  await page.reload()
  await expect(page.getByRole('region', { name: 'Galta canvas, 0 objects', exact: true })).toBeVisible()
  await page.locator('.excalidraw').focus(); await page.keyboard.press('e')
  await expect(eraser).toHaveAttribute('aria-pressed', 'true')
})

test('font defaults, selected text metrics, arbitrary size and alignment survive undo and reload', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${acceptanceOrigin}/sidepanel/index.html`)
  await page.getByRole('button', { name: 'Text — T', exact: true }).click()
  await page.getByRole('button', { name: 'Drawing style', exact: true }).click()
  await choose(page, 'Font', 'Nunito')
  await expect(page.getByRole('slider', { name: 'Stroke width', exact: true })).toHaveCount(0)
  await expect(page.getByRole('group', { name: 'Fill color', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.mouse.click(450, 240)
  await page.locator('.excalidraw-wysiwyg').fill('A place to think\nA little room to draw')
  await page.keyboard.press('Escape')
  await expect.poll(async () => (await elements(page))[0]?.fontFamily).toBe(6)
  const before = (await elements(page))[0]
  await selectAll(page)
  await page.getByRole('button', { name: 'Drawing style', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Font', exact: true })).toHaveText('Nunito')
  await choose(page, 'Font', 'Cascadia')
  await expect.poll(async () => (await elements(page))[0].fontFamily).toBe(3)
  await expect.poll(async () => (await elements(page))[0].width).not.toBe(before.width)
  await page.keyboard.press('Escape'); await page.locator('.excalidraw').focus(); await page.keyboard.press('Meta+z')
  await expect.poll(async () => (await elements(page))[0].fontFamily).toBe(6)
  await page.keyboard.press('Meta+Shift+z')
  await expect.poll(async () => (await elements(page))[0].fontFamily).toBe(3)
  await page.getByRole('button', { name: 'Drawing style', exact: true }).click()
  await page.getByRole('spinbutton', { name: 'Font size', exact: true }).fill('37')
  await page.getByRole('spinbutton', { name: 'Font size', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Align Center', exact: true }).click()
  const color = page.getByRole('textbox', { name: 'Text color value', exact: true })
  await color.fill('#123456'); await color.press('Enter')
  await expect.poll(async () => (await elements(page))[0]).toMatchObject({ fontFamily: 3, fontSize: 37, textAlign: 'center', strokeColor: '#123456' })
  const changed = (await elements(page))[0]
  expect(changed.height).toBeGreaterThan(before.height)
  await page.screenshot({ path: info.outputPath('text-style.png') })
  await page.reload(); await selectAll(page)
  await page.getByRole('button', { name: 'Drawing style', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Font', exact: true })).toHaveText('Cascadia')
  await expect(page.getByRole('spinbutton', { name: 'Font size', exact: true })).toHaveValue('37')
  await expect(page.getByRole('button', { name: 'Align Center', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect((await elements(page))[0]).toMatchObject({ width: changed.width, height: changed.height })
  expect(errors).toEqual([])
})

