test('bound text reflows with its container when changing type and size', async ({ page }) => {
  await page.goto(`${acceptanceOrigin}/sidepanel/index.html`)
  await page.getByRole('button', { name: 'Shapes and more tools', exact: true }).click()
  await page.getByRole('button', { name: 'Rectangle', exact: true }).click()
  await page.mouse.move(400, 200); await page.mouse.down(); await page.mouse.move(680, 350); await page.mouse.up()
  await page.mouse.dblclick(520, 270)
  await page.locator('.excalidraw-wysiwyg').fill('Words inside a shape')
  await page.keyboard.press('Escape')
  await selectAll(page)
  await page.getByRole('button', { name: 'Drawing style', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Vertical', exact: true })).toBeVisible()
  await choose(page, 'Font', 'Lilita One')
  await page.getByRole('spinbutton', { name: 'Font size', exact: true }).fill('48')
  await page.getByRole('spinbutton', { name: 'Font size', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Vertical Bottom', exact: true }).click()
  await expect.poll(async () => (await elements(page)).find((el: any) => el.type === 'text')).toMatchObject({ fontFamily: 7, fontSize: 48, verticalAlign: 'bottom' })
  const all = await elements(page), text = all.find((el: any) => el.type === 'text'), rect = all.find((el: any) => el.id === text.containerId)
  expect(rect.boundElements).toContainEqual({ id: text.id, type: 'text' })
  expect(text.x).toBeGreaterThanOrEqual(rect.x)
  expect(text.y).toBeGreaterThanOrEqual(rect.y)
  expect(text.y + text.height).toBeLessThanOrEqual(rect.y + rect.height)
})

test('arrow controls use native paths and endpoints, and one slider gesture is one undo', async ({ page }, info) => {
  await page.goto(`${acceptanceOrigin}/sidepanel/index.html`)
  await page.getByRole('button', { name: 'Shapes and more tools', exact: true }).click()
  await page.getByRole('button', { name: 'Arrow', exact: true }).click()
  await page.mouse.move(420, 200); await page.mouse.down(); await page.mouse.move(660, 380); await page.mouse.up()
  await expect.poll(async () => (await elements(page))[0]?.type).toBe('arrow')
  await page.getByRole('button', { name: 'Drawing style', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Fill color', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Path Elbow', exact: true }).click()
  await choose(page, 'Start', 'Open circle')
  await choose(page, 'End', 'Triangle')
  await page.getByRole('button', { name: 'Line Dashed', exact: true }).click()
  await expect.poll(async () => (await elements(page))[0]).toMatchObject({ elbowed: true, startArrowhead: 'circle_outline', endArrowhead: 'triangle', strokeStyle: 'dashed' })
  const before = (await elements(page))[0].opacity
  const slider = page.getByRole('slider', { name: 'Opacity', exact: true })
  const track = await slider.locator('..').boundingBox()
  await page.mouse.move(track!.x + track!.width - 5, track!.y + track!.height / 2); await page.mouse.down()
  await page.mouse.move(track!.x + track!.width / 2, track!.y + track!.height / 2, { steps: 12 }); await page.mouse.up()
  await expect.poll(async () => (await elements(page))[0].opacity).toBeLessThan(before)
  await page.screenshot({ path: info.outputPath('arrow-style.png') })
  await page.keyboard.press('Escape'); await page.locator('.excalidraw').focus(); await page.keyboard.press('Meta+z')
  await expect.poll(async () => (await elements(page))[0].opacity).toBe(before)
})

for (const touch of [false, true]) test(`text style controls fit a narrow ${touch ? 'touch' : 'mouse'} panel`, async ({ browser }, info) => {
  const context = await browser.newContext({ viewport: { width: 320, height: 540 }, hasTouch: touch })
  const page = await context.newPage()
  try {
    await page.goto(`${acceptanceOrigin}/sidepanel/index.html`)
    await page.getByRole('button', { name: 'Text — T', exact: true }).click()
    await page.getByRole('button', { name: 'Drawing style', exact: true }).click()
    const panel = page.getByRole('dialog', { name: 'Drawing style', exact: true })
    const bounds = (await panel.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(8)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(312)
    expect(bounds.y).toBeGreaterThanOrEqual(8)
    expect(bounds.y + bounds.height).toBeLessThanOrEqual(532)
    expect(await panel.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await choose(page, 'Font', 'Nunito')
    for (const control of await panel.locator('button:visible, input:visible').all()) {
      await control.scrollIntoViewIfNeeded()
      const rect = (await control.boundingBox())!
      const box = (await panel.boundingBox())!
      expect(rect.x).toBeGreaterThanOrEqual(box.x)
      expect(rect.x + rect.width).toBeLessThanOrEqual(box.x + box.width)
      expect(await control.evaluate(el => { const r = el.getBoundingClientRect(); return el.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)) })).toBe(true)
      if (touch && await control.evaluate(el => el.tagName === 'BUTTON')) {
        expect(rect.width).toBeGreaterThanOrEqual(44)
        expect(rect.height).toBeGreaterThanOrEqual(44)
      }
    }
    await panel.evaluate(el => { el.scrollTop = 0 })
    await page.screenshot({ path: info.outputPath('text-style-narrow.png') })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Drawing style', exact: true })).toBeFocused()
  } finally { await context.close() }
})
